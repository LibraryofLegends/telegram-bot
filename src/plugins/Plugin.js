'use strict';

class Plugin {

    /**
     * ============================================================
     * Konstruktor
     * ============================================================
     */

    constructor({

        name,

        version = '1.0.0',

        author = 'Unknown',

        description = ''

    }) {

        this.name = name;

        this.version = version;

        this.author = author;

        this.description = description;

        this.enabled = true;

        this.loaded = false;

    }

    /**
     * ============================================================
     * Laden
     * ============================================================
     */

    async load(container) {

        this.loaded = true;

    }

    /**
     * ============================================================
     * Starten
     * ============================================================
     */

    async start(container) {

    }

    /**
     * ============================================================
     * Stoppen
     * ============================================================
     */

    async stop(container) {

    }

    /**
     * ============================================================
     * Entladen
     * ============================================================
     */

    async unload(container) {

        this.loaded = false;

    }

    /**
     * ============================================================
     * Aktivieren
     * ============================================================
     */

    enable() {

        this.enabled = true;

    }

    /**
     * ============================================================
     * Deaktivieren
     * ============================================================
     */

    disable() {

        this.enabled = false;

    }

    /**
     * ============================================================
     * Status
     * ============================================================
     */

    isEnabled() {

        return this.enabled;

    }

    /**
     * ============================================================
     * Geladen
     * ============================================================
     */

    isLoaded() {

        return this.loaded;

    }

    /**
     * ============================================================
     * Informationen
     * ============================================================
     */

    info() {

        return {

            name: this.name,

            version: this.version,

            author: this.author,

            description: this.description,

            enabled: this.enabled,

            loaded: this.loaded

        };

    }

}

module.exports = Plugin;