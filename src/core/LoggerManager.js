'use strict';

const Logger = require('./Logger');

class LoggerManager {

    /**
     * ============================================================
     * Konstruktor
     * ============================================================
     */

    constructor(options = {}) {

        this.options = options;

        this.loggers = new Map();

    }

    /**
     * ============================================================
     * Logger abrufen
     * ============================================================
     */

    get(module) {

        if (!this.loggers.has(module)) {

            this.loggers.set(
                module,
                new Logger({
                    ...this.options,
                    module
                })
            );

        }

        return this.loggers.get(module);

    }

    /**
     * ============================================================
     * Vorhanden
     * ============================================================
     */

    has(module) {

        return this.loggers.has(module);

    }

    /**
     * ============================================================
     * Entfernen
     * ============================================================
     */

    remove(module) {

        this.loggers.delete(module);

    }

    /**
     * ============================================================
     * Zurücksetzen
     * ============================================================
     */

    clear() {

        this.loggers.clear();

    }

    /**
     * ============================================================
     * Liste
     * ============================================================
     */

    list() {

        return [...this.loggers.keys()];

    }

    /**
     * ============================================================
     * Informationen
     * ============================================================
     */

    info() {

        return {

            loggerCount: this.loggers.size,

            modules: this.list()

        };

    }

}

module.exports = LoggerManager;