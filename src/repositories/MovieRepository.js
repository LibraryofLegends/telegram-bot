'use strict';

const BaseRepository = require('./BaseRepository');

class MovieRepository extends BaseRepository {

    /**
     * ============================================================
     * Konstruktor
     * ============================================================
     */

    constructor(db) {

        super(db, 'movies');

    }

    /**
     * ============================================================
     * TMDB
     * ============================================================
     */

    findByTMDB(tmdbId) {

        return this.findOne({
            tmdb_id: tmdbId
        });

    }

    /**
     * ============================================================
     * IMDb
     * ============================================================
     */

    findByIMDb(imdbId) {

        return this.findOne({
            imdb_id: imdbId
        });

    }

    /**
     * ============================================================
     * Library ID
     * ============================================================
     */

    findByLibraryId(id) {

        return this.findOne({
            library_id: id
        });

    }

    /**
     * ============================================================
     * Titel
     * ============================================================
     */

    findByTitle(title) {

        return this.search([
            'title',
            'original_title'
        ], title);

    }

    /**
     * ============================================================
     * Genre
     * ============================================================
     */

    findByGenre(name) {

        return this.search([
            'genres'
        ], name);

    }

    /**
     * ============================================================
     * Sammlung
     * ============================================================
     */

    findByCollection(name) {

        return this.search([
            'collections'
        ], name);

    }

    /**
     * ============================================================
     * Regisseur
     * ============================================================
     */

    findByDirector(name) {

        return this.search([
            'directors'
        ], name);

    }

    /**
     * ============================================================
     * Schauspieler
     * ============================================================
     */

    findByActor(name) {

        return this.search([
            'cast'
        ], name);

    }

    /**
     * ============================================================
     * Sprache
     * ============================================================
     */

    findByLanguage(language) {

        return this.findAll({
            language
        });

    }

    /**
     * ============================================================
     * Land
     * ============================================================
     */

    findByCountry(country) {

        return this.findAll({
            country
        });

    }

    /**
     * ============================================================
     * Qualität
     * ============================================================
     */

    findByQuality(quality) {

        return this.findAll({
            quality
        });

    }

    /**
     * ============================================================
     * Auflösung
     * ============================================================
     */

    findByResolution(resolution) {

        return this.findAll({
            resolution
        });

    }

    /**
     * ============================================================
     * Favoriten
     * ============================================================
     */

    favorites() {

        return this.findAll({
            favorite: true
        });

    }

    /**
     * ============================================================
     * Gesehen
     * ============================================================
     */

    watched() {

        return this.findAll({
            watched: true
        });

    }

    /**
     * ============================================================
     * Ungesehen
     * ============================================================
     */

    unwatched() {

        return this.findAll({
            watched: false
        });

    }

}

module.exports = MovieRepository;